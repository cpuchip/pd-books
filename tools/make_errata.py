"""make_errata.py: build a book's errata.yaml from its source plus the errata we found ourselves.

    python tools/make_errata.py books/thompson-calculus-made-easy-1914

Transcriber-marked errata are read from the source's \\DPtypo{printed}{corrected} marks (Project
Gutenberg's Distributed Proofreaders convention), so the list cannot drift from the file. Errata we
found, and candidates, are read from found.json beside errata.yaml, each with its evidence.
Spacing- and punctuation-only marks are kept but labelled as such. Output is YAML written by hand
as JSON-style quoted scalars, valid YAML with no library needed. collect(book) returns the same
entries as dicts (tools/publish_shelf.py merges them into the site export).

Ids: T### transcriber-marked (numbered in source order), F### found by us, C### candidates,
G### slips in the Gutenberg transcription itself (settled against a scan).
"""
import json
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
FIELDS = ("kind", "status", "page", "location", "printed", "corrected", "class", "evidence", "found_by", "date")


def q(s):
    return json.dumps(s, ensure_ascii=False)


def collect(book):
    book = Path(book)
    meta = json.loads((book / "book.json").read_text(encoding="utf-8"))
    src = (book / "source" / meta["source_file"]).read_text(encoding="utf-8").replace("\r\n", "\n")
    pages = [(m.start(), m.group(1)) for m in re.finditer(r"\\DPPageSep\{[^}]*\}\{([^}]*)\}", src)]

    def page(pos):
        p = None
        for s, n in pages:
            if s > pos:
                break
            p = n
        return p

    entries = []
    for m in re.finditer(r"\\DPtypo\{((?:[^{}]|\{[^{}]*\})*)\}\{((?:[^{}]|\{[^{}]*\})*)\}", src):
        printed, corrected = m.group(1), m.group(2)
        if printed == corrected == "":
            continue  # the transcriber's own documentation of the macro, not a mark in the text
        trivial = re.sub(r"[\s.,;:~]", "", printed) == re.sub(r"[\s.,;:~]", "", corrected)
        ctx = re.sub(r"\s+", " ", src[max(0, m.start() - 70):m.start()]).strip()[-60:]
        entries.append({"id": f"T{len(entries) + 1:03d}", "kind": "transcriber-marked", "page": page(m.start()),
                        "printed": printed, "corrected": corrected,
                        "class": "spacing-or-punctuation" if trivial else "content", "context": ctx,
                        "found_by": "Project Gutenberg Distributed Proofreaders (marked in the source)"})
    marked = len(entries)
    found = book / "found.json"
    for e in json.loads(found.read_text(encoding="utf-8")) if found.exists() else []:
        entries.append({"id": e["id"], **{k: e[k] for k in FIELDS if k in e}})
    return meta, entries, marked


def main():
    book = Path(sys.argv[1])
    meta, entries, marked = collect(book)
    out = [f"# Errata for {meta['title']} ({meta['edition']}).",
           "# GENERATED by tools/make_errata.py from the source's \\DPtypo marks and found.json; edit found.json, not this file.",
           f"book: {q(meta['title'])}", f"edition: {q(meta['edition'])}", f"source: {q(meta['source_file'])}",
           "errata:"]
    for e in entries:
        out.append(f"  - id: {q(e['id'])}")
        for k in ("kind", "status", "page", "location", "printed", "corrected", "class", "context", "evidence",
                  "found_by", "date"):
            if k in e:
                out.append(f"    {k}: {q(e[k])}")
    (book / "errata.yaml").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{book.name}: {marked} transcriber-marked, {len(entries) - marked} found or candidate")


if __name__ == "__main__":
    main()
